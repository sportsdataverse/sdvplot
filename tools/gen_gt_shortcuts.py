"""Write ``src/sdvplot/great_tables/_gt_shortcuts.py``: one thin ``gt_theme_<id>`` per CURATED registry theme.

uv run python tools/gen_gt_shortcuts.py          # rewrite the file
uv run python tools/gen_gt_shortcuts.py --check  # exit 1 if it would change (CI and tests)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "sdvplot" / "great_tables" / "_gt_shortcuts.py"
# the 04-synthesis shortlist of the table-design survey, under the sources' real names
CURATED = [
    "basketball-reference",
    "datagolf",
    "fivethirtyeight-site",
    "wikipedia",
    "cleaning-the-glass",
    "bbc-sport",
    "opta-analyst",
    "our-world-in-data",
    "bloomberg-markets",
    "aer",
    "nzz",
    "guardian",
    "barttorvik",
    "espn-site",
    "gov-uk",
    "washington-post",
    "reuters-graphics",
    "formula1",
    "dunks-and-threes",
    "economist",
]

HEADER = '''"""GENERATED by tools/gen_gt_shortcuts.py - do not edit. One ``gt_theme_<id>`` per curated theme."""

from __future__ import annotations

from great_tables import GT

from sdvplot.great_tables._source_themes import gt_theme_source

__all__ = [
{names}
]
'''

FUNC = '''

def {fn}(gt: GT, mode: str = "light", density: str = "comfortable") -> GT:
    """Style a table like {source} (``gt_theme_source(gt, "{id}")``).

    Args:
        gt: The great_tables ``GT`` to theme.
        mode: ``"light"`` or ``"dark"``; ``"dark"`` raises when this theme is light-only.
        density: The type and padding scale: "comfortable", "compact" or "social".

    Returns:
        GT: A new ``GT`` with the theme applied.

    Raises:
        TypeError: ``gt`` is not a great_tables ``GT``.
        InputError: (a ValueError) ``mode`` is invalid, or ``"dark"`` for a light-only theme.
        ValueError: ``density`` is not one of the three scales.

    Example:
        ::

            from great_tables import GT
            import polars as pl
            from sdvplot.great_tables import {fn}

            df = pl.DataFrame({{"team": ["KC", "BUF", "BAL"], "wins": [12, 10, 9]}})

            {fn}(GT(df))

    See Also:
        sdvplot.great_tables.gt_theme_source: any of the 122 surveyed themes by id
    """
    return gt_theme_source(gt, "{id}", mode=mode, density=density)
'''


def shortcut_name(theme_id: str) -> str:
    return "gt_theme_" + theme_id.replace("-", "_")


def render() -> str:
    from sdvplot._table_themes import _registry

    reg = _registry()
    missing = [i for i in CURATED if i not in reg]
    if missing:
        raise SystemExit(f"CURATED ids not in the registry: {missing}")
    names = "\n".join(f'    "{shortcut_name(i)}",' for i in sorted(CURATED, key=shortcut_name))
    body = "".join(FUNC.format(fn=shortcut_name(i), id=i, source=reg[i]["source"]) for i in CURATED)
    return HEADER.format(names=names) + body


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_bytes().decode("utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.name} is out of date: run `uv run python tools/gen_gt_shortcuts.py`", file=sys.stderr)
            return 1
        return 0
    OUT.write_bytes(text.encode("utf-8"))  # bytes: LF on Windows too
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
